-- 047: 社媒矩阵加装包 —— 用户额度与到期
--
-- 背景（定价 v2，2026-09-17 定）：社媒矩阵**完全不进套餐**（basic → trade-flagship
-- 全部 0 组），任何用户想用都必须**单独购买加装包**。计价单位是「品牌账号组」：
-- 1 组 = 1 个品牌 × 5 个平台各 1 个账号。
--
-- ── 为什么额度口径是「各平台账号数的最大值」而不是「账号总数」────────────
-- 加装包的成本由聚合商（Ayrshare）决定，而它是**按 Profile 计费、不按平台位**：
-- 一个 Profile 可以连满全部平台的各一个账号而不加钱，只有**同一平台第 2 个账号**
-- 才占用第 2 个 Profile。所以：
--   · LinkedIn + FB + IG + YT + TikTok 各 1 个  → 1 组（成本 = 1 个 Profile）
--   · 再加一个 FB 主页（同平台第 2 个）        → 2 组（成本 = 2 个 Profile）
-- 若按「账号总数」计（上面第一例会算成 5 组），会对客户严重超收，也与我们的实际
-- 成本完全脱钩。**这是本模块最容易搞错的一点，改动前先读这段。**
--
-- ── 为什么落到 `users` 而不是新建一张订阅表 ──────────────────────────────
-- 语义刻意做成**账户级单值**：组数一个值、到期一个值。再次购买时组数**累加**、
-- 到期从「原到期日与当前时间的较晚者」顺延。这避免为多批次额度引入一整套
-- 「订阅条目表 + 逐条到期 + 逐条核销」的复杂度，而当前业务（一次性加装包、
-- 手动续费、组数只增不减）完全够用。
-- 局限已知且可接受：若客户分两次买、希望两批额度各自独立到期，本模型无法表达
-- （后买的那批会把先买那批的到期一起往后推）。真要细分时再引入条目表。
--
-- ⚠️ 不加进 `User` 结构体：`sqlite_user.rs` 多处用 `SELECT * FROM users` 映射
-- `User`，给结构体加字段会牵动所有查询的列对齐。额度读写一律走
-- `IUserRepository::get_social_entitlement` / `grant_social_addon` 两个专用方法。
--
-- 本迁移**不新增产品表**，因此无需改动 `id_schema_contract.rs` 的任何登记项。

-- 已购买的品牌账号组数（0 = 未购买，社媒功能整体不可用）。
ALTER TABLE users ADD COLUMN social_groups INTEGER NOT NULL DEFAULT 0;

-- 加装包到期时间（epoch millis）。NULL = 无到期（后台手工开通）。
ALTER TABLE users ADD COLUMN social_expires_at INTEGER;
