-- 033_expert_market.sql
-- 专家数字分身市场：目录 + 雇佣授权（Phase0 内置专家种子）
--
-- 模式遵循 v3 契约：物理主键 `id INTEGER PRIMARY KEY AUTOINCREMENT`，
-- 业务身份列（expert_id / license_id / user_id）为 UUIDv7 文本并带 GLOB CHECK。

CREATE TABLE expert_catalog (
    id                    INTEGER PRIMARY KEY AUTOINCREMENT,
    expert_id            TEXT NOT NULL UNIQUE
                          CHECK (
                              length(expert_id) = 36
                              AND lower(expert_id) = expert_id
                              AND expert_id GLOB '????????-????-7???-[89ab]???-????????????'
                              AND replace(expert_id, '-', '') NOT GLOB '*[^0-9a-f]*'
                          ),
    slug                 TEXT NOT NULL UNIQUE,
    name                 TEXT NOT NULL,
    title                TEXT NOT NULL,
    description          TEXT,
    avatar               TEXT,
    tags                 TEXT NOT NULL DEFAULT '[]',
    category             TEXT,
    price_credits        INTEGER NOT NULL DEFAULT 0,
    persona_custom      TEXT NOT NULL DEFAULT '',
    persona_preset      TEXT NOT NULL DEFAULT 'lively',
    default_character   TEXT NOT NULL DEFAULT 'mochi',
    default_model_provider TEXT,
    default_model       TEXT,
    default_skills      TEXT NOT NULL DEFAULT '[]',
    is_builtin          INTEGER NOT NULL DEFAULT 1,
    creator_id          TEXT,
    enabled             INTEGER NOT NULL DEFAULT 1,
    sort_order          INTEGER NOT NULL DEFAULT 0,
    created_at          INTEGER NOT NULL DEFAULT 0
);

CREATE INDEX idx_expert_catalog_category ON expert_catalog (category);
CREATE INDEX idx_expert_catalog_enabled  ON expert_catalog (enabled);
CREATE INDEX idx_expert_catalog_creator  ON expert_catalog (creator_id);

CREATE TABLE user_expert_licenses (
    id              INTEGER PRIMARY KEY AUTOINCREMENT,
    license_id     TEXT NOT NULL UNIQUE
                    CHECK (
                        length(license_id) = 36
                        AND lower(license_id) = license_id
                        AND license_id GLOB '????????-????-7???-[89ab]???-????????????'
                        AND replace(license_id, '-', '') NOT GLOB '*[^0-9a-f]*'
                    ),
    user_id        TEXT NOT NULL
                    CHECK (
                        length(user_id) = 36
                        AND lower(user_id) = user_id
                        AND user_id GLOB '????????-????-7???-[89ab]???-????????????'
                        AND replace(user_id, '-', '') NOT GLOB '*[^0-9a-f]*'
                    ),
    expert_id      TEXT NOT NULL
                    CHECK (
                        length(expert_id) = 36
                        AND lower(expert_id) = expert_id
                        AND expert_id GLOB '????????-????-7???-[89ab]???-????????????'
                        AND replace(expert_id, '-', '') NOT GLOB '*[^0-9a-f]*'
                    ),
    -- 雇佣后生成的数字分身 Companion 实例 ID（回链）。companions 以文件存储，
    -- 此处仅作 opaque 引用，列名刻意不以 `_id` 结尾，不进入 v3 逻辑引用契约。
    companion_ref TEXT,
    tx_id          TEXT,
    source         TEXT NOT NULL DEFAULT 'purchase',
    purchased_at   INTEGER NOT NULL,
    expiry_at      INTEGER
);

CREATE INDEX idx_user_expert_licenses_user   ON user_expert_licenses (user_id);
CREATE INDEX idx_user_expert_licenses_expert ON user_expert_licenses (expert_id);
CREATE INDEX idx_user_expert_licenses_companion ON user_expert_licenses (companion_ref);

